import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = fileURLToPath(new URL('../', import.meta.url));
const app = path.join(root, 'app');
const read = f => JSON.parse(fs.readFileSync(path.join(app, 'data', f), 'utf8').replace(/^\uFEFF/, ''));
const assert = (x, m) => { if (!x) throw new Error(m); };
const data = read('round2.json');
const trial = read('retrieval-trial.json');
const first = read('research.json');
const inputs = trial.records.filter(p => p.decision === 'retain');
const same = (a, b) => JSON.stringify([...a].sort()) === JSON.stringify([...b].sort());
assert(data.papers.length === 17 && new Set(data.papers.map(p => p.id)).size === 17, 'Second-round identities lost or duplicated');
assert(same(data.papers.map(p => p.id), inputs.map(p => p.id)), 'Candidate set changed');
assert(data.papers.filter(p => p.priorId).length === 9 && data.papers.filter(p => !p.priorId).length === 8, 'Overlap accounting differs');
const ids = new Set(data.papers.map(p => p.id));
for (const p of data.papers) {
  assert(inputs.find(x => x.id === p.id)?.doi.toLowerCase() === p.doi.toLowerCase(), `DOI drift ${p.id}`);
  assert((first.papers.find(x => x.doi.toLowerCase() === p.doi.toLowerCase())?.id || null) === p.priorId, `First-round mapping drift ${p.id}`);
  assert(['full_text', 'sections', 'abstract', 'metadata'].includes(p.accessLevel), `Unknown read scope ${p.id}`);
  assert(['direct', 'mixture_context', 'thesis_context', 'unresolved'].includes(p.eligibility), `Unknown eligibility ${p.id}`);
  assert(p.readingLog.length && p.findings.length && p.limitations.length && p.fullTextAttempt.status && p.fullTextAttempt.reason, `Missing reading trail ${p.id}`);
  assert(Object.keys(p.design).length === 9, `Missing design fields ${p.id}`);
  for (const f of p.findings) assert(f.locator && /^https:\/\//.test(f.sourceUrl) && f.strength, `Unlocated evidence ${p.id}`);
  for (const l of p.readingLog) assert(/^https:\/\//.test(l.url) && l.result && l.readParts && l.locator && l.accessedAt, `Incomplete access log ${p.id}`);
  if (p.accessLevel === 'full_text') assert(p.sources.some(s => s.readScope && !/^abstract$/i.test(s.readScope)), `No full-text reading scope ${p.id}`);
}
for (const c of data.conclusions) assert(c.evidenceIds.length && c.evidenceIds.every(id => ids.has(id)) && c.limit, 'Unclosed conclusion evidence');
for (const t of data.tensions) assert(t.scholarConfirmation === 'pending', 'AI must not self-confirm researcher judgment');
assert(data.corpus.readingLevels.full_text === data.papers.filter(p => p.accessLevel === 'full_text').length, 'Full-text count drift');
const embedded = fs.readFileSync(path.join(app, 'data/round2-data.js'), 'utf8');
assert(JSON.stringify(JSON.parse(embedded.replace(/^window\.ROUND2_DATA = /, '').replace(/;\s*$/, ''))) === JSON.stringify(data), 'Embedded second-round data differs');
for (const manifest of data.inputManifest) assert(crypto.createHash('sha256').update(fs.readFileSync(path.join(root, manifest.file))).digest('hex') === manifest.sha256, `Reading input hash differs ${manifest.file}`);
for (const file of ['round2.json', 'round2-data.js', 'round2-report.md', 'round2-protocol.md', 'round2-review.md', 'round2-evidence.csv']) assert(fs.statSync(path.join(app, 'data', file)).size > 100, `Missing round-two artifact ${file}`);
const csv = fs.readFileSync(path.join(app, 'data/round2-evidence.csv'), 'utf8');
assert(data.papers.every(p => csv.includes(p.id) && csv.includes(p.doi)), 'CSV loses evidence rows');
const html = fs.readFileSync(path.join(app, 'index.html'), 'utf8');
assert(html.indexOf('id="round2-results"') < html.indexOf('id="understanding"'), 'Latest results must precede library details');
assert(html.includes('class="research-entry"') && html.includes('class="r2-nav"'), 'Missing prominent results entry');
assert(fs.readFileSync(path.join(root, '.gitignore'), 'utf8').includes('/research/round2/raw/'), 'Raw reading copies must remain local');
for (const file of ['round2.js', 'data/round2-data.js']) execFileSync(process.execPath, ['--check', path.join(app, file)]);
console.log(JSON.stringify({result: 'pass', round2: data.corpus, conclusions: data.conclusions.length, tensions: data.tensions.length, boundary: 'Artifact and evidence-trail integrity; not scientific reliability certification.'}, null, 2));
