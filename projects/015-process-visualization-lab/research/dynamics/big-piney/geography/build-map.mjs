import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const raw = readFileSync(new URL('./nhd-flowlines.geojson', import.meta.url));
const sourceSha256 = '1f948fb8f9ede292661c0b2c684f1300422f062dc7dd4a96abc8bf53f41abb68';
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
assert.equal(digest(raw), sourceSha256, 'NHD source hash');
const source = JSON.parse(raw);
assert.equal(source.type, 'FeatureCollection');
assert.equal(source.features.length, 15);

const coordinates = source.features.map(feature => {
  assert.equal(feature.properties.gnis_name, 'Big Piney River');
  assert.equal(feature.geometry.type, 'LineString');
  return feature.geometry.coordinates.map(point => point.map(value => Number(value.toFixed(7))));
});
const geography = {
  reach: {
    type: 'MultiLineString',
    coordinates,
    source: 'USGS National Hydrography Dataset · Flowline - Large Scale',
    sourceUrl: 'https://hydro.nationalmap.gov/arcgis/rest/services/nhd/MapServer/6/query?where=GNIS_NAME%3D%27Big%20Piney%20River%27&geometry=-92.095%2C37.79%2C-92.05%2C37.834&geometryType=esriGeometryEnvelope&inSR=4326&outSR=4326&spatialRel=esriSpatialRelIntersects&outFields=GNIS_NAME%2CREACHCODE%2CFCODE&f=geojson',
    sourceSha256,
  },
  imagery: {
    url: 'assets/events/big-piney-usgs-ortho.jpg',
    bbox: [-92.109, 37.777, -92.037, 37.851],
    width: 1440,
    height: 1480,
    crs: 'EPSG:4326',
    source: 'USGS The National Map · USGSImageryOnly',
    sourceUrl: 'https://basemap.nationalmap.gov/arcgis/rest/services/USGSImageryOnly/MapServer/export?bbox=-92.109%2C37.777%2C-92.037%2C37.851&bboxSR=4326&imageSR=4326&size=1440%2C1480&format=jpg&f=image',
    sourceSha256: 'd7226eda6cbd0f472f5e80de3a58da6ec1bfee1c0533d1221ea2d1a9da1918c1',
  },
};
const project = new URL('../../../../', import.meta.url);
assert.equal(digest(readFileSync(new URL('app/' + geography.imagery.url, project))), geography.imagery.sourceSha256, 'USGS basemap hash');
const destination = new URL('app/river-big-piney-geography.js', project);
const output = '// Generated by research/dynamics/big-piney/geography/build-map.mjs\nexport const BIG_PINEY_GEOGRAPHY = ' + JSON.stringify(geography, null, 2).replace(/\[\s+(-?[\d.]+),\s+(-?[\d.]+)\s+\]/g, '[$1, $2]') + ';\n';
if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), output);
else writeFileSync(destination, output);
